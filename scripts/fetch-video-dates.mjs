#!/usr/bin/env node
// scripts/fetch-video-dates.mjs
//
// Fills in the real YouTube upload date for every Quick Lesson, so
// VideoObject.uploadDate stops being a per-batch guess. Every /shorts page
// used to declare a hardcoded 2026-10-01; it now declares a batch date, which
// is better but still not the date Google is being told about.
//
// WHY THIS IS A LOCAL SCRIPT AND NOT A CI JOB
// yt-dlp from a datacentre IP gets "Sign in to confirm you're not a bot" on
// every request — tested, 0 of 56 video IDs resolved from a cloud runner. It
// works from a machine with a signed-in browser, which means your Mac. The
// YouTube Data API v3 path works from anywhere but needs a key.
//
// USAGE (on your Mac)
//
//   brew install yt-dlp          # once
//   node scripts/fetch-video-dates.mjs            # uses your Chrome cookies
//   node scripts/fetch-video-dates.mjs --browser safari
//
//   # or, with a YouTube Data API key and no yt-dlp at all:
//   YOUTUBE_API_KEY=xxx node scripts/fetch-video-dates.mjs --api
//
// It prints a report and writes lib/video-dates.json. Nothing is guessed: a
// video that cannot be resolved is listed as unresolved and left alone.

import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { readFile, writeFile } from 'node:fs/promises'
import { glob } from 'node:fs/promises'

const run = promisify(execFile)
const args = process.argv.slice(2)
const useApi = args.includes('--api')
const browser = (() => {
  const i = args.indexOf('--browser')
  return i >= 0 ? args[i + 1] : 'chrome'
})()

/** Pull every YouTube id out of the shorts data files, keyed by lesson slug. */
async function collectIds() {
  const files = []
  for await (const f of glob('lib/shorts*.ts')) files.push(f)
  const bySlug = new Map()
  for (const f of files.sort()) {
    const src = await readFile(f, 'utf8')
    const re = /slug:\s*'([^']+)'[\s\S]{0,1200}?ids:\s*\[([^\]]*)\]/g
    let m
    while ((m = re.exec(src))) {
      const ids = [...m[2].matchAll(/'([A-Za-z0-9_-]{8,})'/g)].map((x) => x[1])
      if (ids.length && !bySlug.has(m[1])) bySlug.set(m[1], ids)
    }
  }
  return bySlug
}

async function viaYtDlp(id) {
  const { stdout } = await run('yt-dlp', [
    '--skip-download',
    '--no-warnings',
    `--cookies-from-browser=${browser}`,
    '--print',
    '%(upload_date)s|%(title)s',
    `https://www.youtube.com/watch?v=${id}`,
  ])
  const [date, title] = stdout.trim().split('\n').pop().split('|')
  return { date, title }
}

async function viaApi(ids) {
  const key = process.env.YOUTUBE_API_KEY
  if (!key) throw new Error('YOUTUBE_API_KEY is not set')
  const out = new Map()
  // The API takes 50 ids per call, so two calls cover the whole channel.
  for (let i = 0; i < ids.length; i += 50) {
    const batch = ids.slice(i, i + 50)
    const url = `https://www.googleapis.com/youtube/v3/videos?part=snippet&id=${batch.join(',')}&key=${key}`
    const res = await fetch(url)
    if (!res.ok) throw new Error(`YouTube API ${res.status}: ${await res.text()}`)
    const data = await res.json()
    for (const item of data.items ?? []) {
      out.set(item.id, {
        date: item.snippet.publishedAt.slice(0, 10).replaceAll('-', ''),
        title: item.snippet.title,
      })
    }
  }
  return out
}

const bySlug = await collectIds()
const allIds = [...new Set([...bySlug.values()].flat())]
console.log(`${bySlug.size} lessons, ${allIds.length} unique video ids\n`)

const meta = new Map()
const unresolved = []

if (useApi) {
  const res = await viaApi(allIds)
  for (const id of allIds) {
    if (res.has(id)) meta.set(id, res.get(id))
    else unresolved.push([id, 'not returned by the API (deleted, private or wrong id)'])
  }
} else {
  for (const [i, id] of allIds.entries()) {
    process.stdout.write(`\r  ${i + 1}/${allIds.length}`)
    try {
      meta.set(id, await viaYtDlp(id))
    } catch (err) {
      unresolved.push([id, String(err.stderr ?? err.message).split('\n').pop().slice(0, 120)])
    }
  }
  process.stdout.write('\n')
}

/** Earliest upload among a lesson's videos is the lesson's publish date. */
const perLesson = {}
for (const [slug, ids] of bySlug) {
  const dates = ids.map((id) => meta.get(id)?.date).filter(Boolean).sort()
  if (dates.length) {
    const d = dates[0]
    perLesson[slug] = `${d.slice(0, 4)}-${d.slice(4, 6)}-${d.slice(6, 8)}`
  }
}

await writeFile(
  'lib/video-dates.json',
  `${JSON.stringify(
    {
      note: 'Real YouTube upload dates, keyed by Quick Lesson slug. Generated by scripts/fetch-video-dates.mjs — do not hand-edit.',
      generated: new Date().toISOString().slice(0, 10),
      dates: perLesson,
    },
    null,
    2,
  )}\n`,
)

console.log(`resolved ${meta.size}/${allIds.length} videos → ${Object.keys(perLesson).length} lesson dates`)
console.log('wrote lib/video-dates.json')
if (unresolved.length) {
  console.log(`\n${unresolved.length} unresolved (left alone, nothing guessed):`)
  for (const [id, why] of unresolved.slice(0, 12)) console.log(`  ${id}  ${why}`)
  if (unresolved.length > 12) console.log(`  …and ${unresolved.length - 12} more`)
}
console.log('\nNext: wire videoPublished in lib/shorts*.ts to these dates, then commit both.')
