// ── Tiny builder for reference solutions ───────────────────────────────────
let n = 0
const id = () => `s${++n}`
const fwd = (steps = 1): Block => ({ id: id(), type: 'forward', n: steps })
const L = (): Block => ({ id: id(), type: 'left' })
const R = (): Block => ({ id: id(), type: 'right' })
const pick = (): Block => ({ id: id(), type: 'pickup' })
const drop = (): Block => ({ id: id(), type: 'drop' })
const penDown = (): Block => ({ id: id(), type: 'penDown' })
const lightOn = (): Block => ({ id: id(), type: 'lightOn' })
const say = (text: string): Block => ({ id: id(), type: 'say', text })
const rep = (times: number, body: Block[]): RepeatBlock => ({ id: id(), type: 'repeat', n: times, body })
const until = (body: Block[]): RepeatUntilBlock => ({ id: id(), type: 'repeatUntil', body })
const ifWall = (body: Block[], elseBody: Block[] = []): IfSenseBlock => ({ id: id(), type: 'ifWall', body, elseBody })
const ifLine = (body: Block[], elseBody: Block[] = []): IfSenseBlock => ({ id: id(), type: 'ifLine', body, elseBody })
const ifColor = (color: TileColor, body: Block[], elseBody: Block[] = []): IfColorBlock => ({ id: id(), type: 'ifColor', color, body, elseBody })

