export function missionsForBand(band: BandId): Mission[] {
  return MISSIONS.filter((m) => m.band === band).sort((a, b) => a.order - b.order)
}

export function getMission(id: string): Mission | undefined {
  return MISSIONS.find((m) => m.id === id)
}

export function toPublic(m: Mission): MissionPublic {
  // eslint-disable-next-line @typescript-eslint/no-unused-vars
  const { solution, ...rest } = m
  return rest
}

/** The mission before this one in its band (it must be solved to unlock this one), or null. */
export function previousInBand(m: Mission): Mission | null {
  return MISSIONS.find((x) => x.band === m.band && x.order === m.order - 1) ?? null
}

