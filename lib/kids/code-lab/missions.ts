// lib/kids/code-lab/missions.ts
// Every Code Lab mission. Grouped by band, unlocked in `order` within a band.
// Each one carries a reference solution that verify.ts runs through the real
// interpreter — a mission that cannot be solved never ships.
//
// Arena legend (see ArenaDef in types.ts):
//   . floor  # wall  S start  G flag  * gem  r g b y colour  = line
//   s sand  k rocks  d dark  D dark+gem  o box  X drop zone  Y yellow+box  B blue drop zone

