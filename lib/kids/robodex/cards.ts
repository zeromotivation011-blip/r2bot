/** Worlds in Robodex order (matches WORLDS in lib/kids/universe/worlds.ts). */
export const ROBODEX_WORLD_ORDER: readonly WorldId[] = ['ocean', 'zoo', 'hospital', 'farm', 'city', 'station', 'guardians']

const BY_ID = new Map(ROBODEX_CARDS.map((c) => [c.id, c]))

export function getRobodexCard(id: string): RobodexCard | undefined {
  return BY_ID.get(id)
}

export function cardsInWorld(world: WorldId): RobodexCard[] {
  return ROBODEX_CARDS.filter((c) => c.world === world)
}

export function isRobodexCardId(x: unknown): x is string {
  return typeof x === 'string' && BY_ID.has(x)
}
