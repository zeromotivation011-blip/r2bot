// after every change.
//
// The ladder, band by band:
//   Explorers  (5–7)  what the robot really needs; choosing parts for a job;
//                     wheels for the ground; body shape follows the job; low
//                     and heavy is stable; sensors for the dark; ramps make
//                     lifting easier; slow and strong gears; build–test–improve.
//   Builders   (8–10) the design process in order; budgets; sizing wheels for
//                     a kerb; wheel size sets speed; balance for ramps both
//                     ways; sensors that see glass; idler gears; battery maths;
//                     safety vs fun; runtime as a requirement.
//   Inventors  (11–13) designing from test data; mass vs runtime on a drone;
//                     how many gear stages; meeting a time spec; machines with
//                     friction; design-to-budget sensors; torque vs wheel size;
//                     braking with a heavy arm; privacy-by-design; a full
//                     field robot.
//   Engineers  (14–17) power budgets; trade-offs without live gauges; losses
//                     per gear mesh; a mixed-terrain course; safety margins;
//                     least effort distance; cheapest sensor suite; launch
//                     decisions and safety cases; failure analysis; a
//                     disaster-response capstone.

